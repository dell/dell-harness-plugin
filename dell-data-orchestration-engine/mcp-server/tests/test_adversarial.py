# --- AT-005 (WITHDRAWN) -----------------------------------------------------------------
# Pattern: Stale input (read-modify-write lost update).
# Assumption challenged: "this caller is the only writer of an item's metadata."
#
# WITHDRAWN as a false positive, and kept here as a record of why. The original test asserted
# that item_update drops a concurrent writer's key, and it failed — but only because the test
# double records the whole `item.metadata` map. The real SDK sends
# `DictDiffer.diff(origin=item._platform_dict, modified=item.to_json())`
# (dtlpy/repositories/items.py:452), i.e. a field-level PATCH of just what this caller
# changed, so a key added by another writer after our read is not overwritten.
#
# This is precisely the failure mode AGENTS.md warns about: a mocked seam inventing a defect
# that does not exist upstream. The residual risk — two writers changing the *same* key —
# cannot be observed offline and is recorded as a live-verification item instead.


