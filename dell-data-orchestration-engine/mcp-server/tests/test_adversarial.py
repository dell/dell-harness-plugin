# --- AT-008 -----------------------------------------------------------------------------
# Pattern: Timing and ordering / resource contention.
# Assumption challenged: "the duplicate check and the create are one atomic step." The MCP
# SDK runs tools in worker threads, so two trigger_create calls genuinely interleave. This
# drives real threads rather than simulating them: the fake's list() reflects what has been
# created, and create() holds a window open, so an unserialised check-then-write loses.


def test_concurrent_trigger_creates_cannot_both_pass_the_duplicate_check(monkeypatch):
    import threading
    import time

    created: list = []
    lock = threading.Lock()

    def make_trigger(**kwargs):
        return SimpleNamespace(
            id=f"trg-{len(created)}",
            name=kwargs.get("name"),
            active=True,
            type="Event",
            resource="Item",
            actions=[
                dl_action.value if hasattr(dl_action, "value") else str(dl_action)
                for dl_action in kwargs.get("actions", [])
            ],
            execution_mode="Once",
            service_id=kwargs.get("service_id"),
            pipeline_id=kwargs.get("pipeline_id"),
            function_name="run",
            project_id="proj-1",
            createdAt="2026-01-01",
        )

    class RacingTriggers:
        def list(self, **_):
            with lock:
                return SimpleNamespace(items=list(created))

        def create(self, **kwargs):
            # Widen the check-then-write window so an unserialised implementation loses.
            time.sleep(0.05)
            entity = make_trigger(**kwargs)
            with lock:
                created.append(entity)
            return entity

    proj = SimpleNamespace(id="proj-1", triggers=RacingTriggers(), pipelines=OwnedRepo("proj-1"))
    monkeypatch.setattr(triggers, "get_project", lambda project_id: proj)
    monkeypatch.setattr(
        triggers,
        "get_dataset",
        lambda project_id, dataset_id: SimpleNamespace(id=dataset_id, name="my-dataset"),
    )

    from mcp import Client

    from doe_mcp.server import build_server
    from tests.conftest import run

    args = {
        "project_id": "proj-1",
        "name": "on-new-image",
        "pipeline_id": "pipe-1",
        "dataset_id": "ds-1",
        "confirm": True,
    }

    def call_once(results, index):
        async def _call():
            async with Client(build_server()) as client:
                return await client.call_tool("trigger_create", args)

        results[index] = run(_call())

    results: dict = {}
    threads = [threading.Thread(target=call_once, args=(results, n)) for n in range(2)]
    for thread in threads:
        thread.start()
    for thread in threads:
        thread.join()

    assert len(created) == 1, (
        "Two identical triggers were created concurrently. Check-then-create is not "
        "serialised, so every matching event now fires the pipeline twice, at double cost."
    )
    # And the loser must be told why, not fail silently.
    assert any(result.is_error for result in results.values())
