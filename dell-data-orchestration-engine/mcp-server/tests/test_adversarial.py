# --- AT-003 -----------------------------------------------------------------------------
# Pattern: Timing and ordering (time-of-check to time-of-use).
# Assumption challenged: "nothing changes between counting the annotations and deleting
# them." The classifier trigger this feature exists to create keeps writing annotations, so
# the set can grow between the count the human confirmed and the delete they authorised.


def test_delete_by_model_refuses_when_the_set_grew_since_the_user_confirmed(monkeypatch):
    class GrowingAnnotations(FakeAnnotations):
        def __init__(self):
            super().__init__()
            self.list_calls = 0
            self.delete_filters = None

        def list(self, filters=None):
            self.list_calls += 1
            # First call: the count shown to the user. Later: the trigger has fired again.
            count = 2 if self.list_calls == 1 else 500
            return SimpleNamespace(items=[], items_count=count)

        def delete(self, annotation_id=None, filters=None, **_):
            self.delete_filters = filters
            return True

    fake = GrowingAnnotations()
    ds = SimpleNamespace(id="ds-1", annotations=fake, labels_flat_dict={"person": object()})
    monkeypatch.setattr(annotations, "get_dataset", lambda project_id, dataset_id: ds)

    from mcp import Client

    from doe_mcp.server import build_server
    from tests.conftest import run

    async def _call():
        async with Client(build_server()) as client:
            # The user was shown 2 and agreed to 2; by now 500 match.
            fake.list()  # the earlier, unconfirmed call that produced the "2"
            return await client.call_tool(
                "annotation_delete_by_model",
                {**ITEM_ARGS, "model_id": "model-1", "confirm": True, "expected_count": 2},
            )

    result = run(_call())

    assert result.is_error is True, (
        "The set grew between confirmation and deletion and the tool deleted anyway: a "
        "confirmation for 2 annotations authorised 500."
    )
    assert fake.delete_filters is None


