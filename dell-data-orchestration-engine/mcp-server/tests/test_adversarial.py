# --- AT-001 -----------------------------------------------------------------------------
# Pattern: Partial failure.
# Assumption challenged: "serialising an uploaded item always succeeds, so the per-file
# outcome record is always produced." The upload loop only guards the platform call; a
# failure while summarising a successfully uploaded item escapes the loop and destroys the
# record of every file already uploaded in that batch.


def test_upload_keeps_the_per_file_record_when_summarising_one_item_fails(monkeypatch, tmp_path):
    good = tmp_path / "good.png"
    bad = tmp_path / "unserialisable.png"
    good.write_bytes(b"x")
    bad.write_bytes(b"x")

    fake = FakeItems()

    def upload(local_path=None, **_):
        if local_path == str(bad):
            # Uploaded fine, but the entity is missing an attribute the summariser reads.
            return SimpleNamespace(id="item-broken")
        return fake_item()

    fake._upload_result = upload
    ds = SimpleNamespace(id="ds-1", name="images", items=fake)
    monkeypatch.setattr(items, "get_dataset", lambda project_id, dataset_id: ds)

    from mcp import Client

    from doe_mcp.server import build_server
    from tests.conftest import run

    async def _call():
        async with Client(build_server()) as client:
            return await client.call_tool("item_upload", {**ITEM_ARGS, "local_paths": [str(good), str(bad)]})

    result = run(_call())

    # The first file really did upload. Whatever happens to the second, the caller must not
    # lose that fact — otherwise a retry re-uploads it.
    assert result.is_error is False, (
        "A failure summarising one item aborted the whole batch, discarding the record of "
        "files that had already uploaded. The caller cannot tell what to retry."
    )
    body = result.structured_content
    assert [entry["local_path"] for entry in body["uploaded"]] == [str(good)]
    assert body["failed"][0]["local_path"] == str(bad)


